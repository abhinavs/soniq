"""Build docs/llms-full.txt from the canonical doc pages.

Run it after you edit one of the pages below:

    python scripts/build_llms_full.py

tests/unit/test_llms_full.py fails when the committed file is out of date.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "llms-full.txt"

# (title, path under docs/, what the page covers)
PAGES = [
    ("Quickstart", "quickstart.md", "canonical end-to-end shape"),
    ("API - Jobs", "api/jobs.md", "decorator, enqueue, schedule, JobContext, cron DSL"),
    ("API - Worker", "api/worker.md", "CLI, run_worker, env-var configuration"),
    ("API - Hooks", "api/hooks.md", "before_job, after_job, on_error"),
    (
        "Guide - FastAPI",
        "guides/fastapi.md",
        "lifespan helper, single-process worker, BackgroundTasks",
    ),
    (
        "Guide - Transactional enqueue",
        "guides/transactional-enqueue.md",
        "SQLAlchemy, asyncpg and psycopg connections",
    ),
    (
        "Reference - Glossary",
        "reference/glossary.md",
        "one-paragraph definitions of every term the docs use",
    ),
]

HEADER = """# Soniq - Full canonical docs (for LLM context)

> This file concatenates the canonical Soniq pages so an agent can load the whole working surface in one fetch. For the indexed list of all docs (including tutorials, guides, recipes, production, migration), see [llms.txt](llms.txt).

> Not included here (fetch separately if you need them): webhook delivery ([recipes/webhook-delivery.md](recipes/webhook-delivery.md), tables `soniq_webhook_endpoints` / `soniq_webhook_deliveries`), job logs (table `soniq_logs`, service `app.logs`), and the task registry ([cli/commands.md#tasks-check](cli/commands.md), table `soniq_task_registry` populated by workers on startup and checked by `soniq tasks-check`). `soniq setup` creates all of these tables; the pages below do not cover them.

> Generated by `scripts/build_llms_full.py`. Do not edit by hand.
"""


def build() -> str:
    parts = [HEADER, "Pages included, in order:\n"]
    parts += [f"{i}. {t} - {what}" for i, (t, _, what) in enumerate(PAGES, 1)]
    parts.append("\n---\n")
    for i, (title, path, _) in enumerate(PAGES, 1):
        body = (ROOT / "docs" / path).read_text().strip()
        parts.append(f"\n# Page {i}: {title}\n\n*(source: docs/{path})*\n\n{body}\n\n")
        parts.append("---\n" if i < len(PAGES) else "")
    return "\n".join(parts).rstrip() + "\n"


if __name__ == "__main__":
    OUT.write_text(build())
    print(f"wrote {OUT.relative_to(ROOT)}")
