"""``soniq migrations export`` - print Soniq's schema for other migration tools."""

from __future__ import annotations

import re
import sys
from typing import List, Optional, Tuple

from ..backends.postgres.migration_runner import MigrationRunner

# Same DDL as MigrationRunner.ensure_migration_table, so a later
# ``soniq setup`` finds the tracking table it expects.
_TRACKING_DDL = """\
CREATE TABLE IF NOT EXISTS soniq_migrations (
    id SERIAL PRIMARY KEY,
    version VARCHAR(255) NOT NULL UNIQUE,
    name TEXT NOT NULL,
    applied_at TIMESTAMP DEFAULT NOW(),
    checksum TEXT
);
CREATE INDEX IF NOT EXISTS idx_soniq_migrations_version
ON soniq_migrations (version);
"""

# Alembic runs op.execute(str) through sqlalchemy.text(), where ":name"
# is a bind parameter. Escape single colons ("::" casts are left alone).
_COLON = re.compile(r"(?<!:):(?=[A-Za-z_])")


def add_migrations_cmd(subparsers) -> None:
    parser = subparsers.add_parser(
        "migrations",
        help="Export Soniq migrations for other tools",
        description="Export Soniq's SQL migrations for use outside 'soniq setup'",
    )
    parser.set_defaults(func=lambda args: parser.print_help() or 1)
    sub = parser.add_subparsers(dest="migrations_command", title="Commands")

    export = sub.add_parser(
        "export",
        help="Print migrations as an Alembic revision or raw SQL",
        description=(
            "Print Soniq's core migrations. Use --alembic for a revision file "
            "or --sql for plain SQL. No database connection is needed."
        ),
    )
    fmt = export.add_mutually_exclusive_group(required=True)
    fmt.add_argument("--alembic", action="store_true", help="Emit an Alembic revision")
    fmt.add_argument("--sql", action="store_true", help="Emit raw SQL")
    export.add_argument(
        "--from",
        dest="from_version",
        metavar="VERSION",
        help="Only export migrations newer than VERSION (for example 0003)",
    )
    export.add_argument(
        "--down-revision",
        default=None,
        metavar="REV",
        help="Alembic down_revision for the generated file (default: None)",
    )
    export.add_argument(
        "--revision",
        default=None,
        metavar="ID",
        help="Alembic revision id (default: soniq_<last version>)",
    )
    export.set_defaults(func=handle_export)


def _select(from_version: Optional[str]) -> List[Tuple[str, str, str]]:
    # "00" is the core range (0001-0099); plugin versions start with "01"+.
    found = MigrationRunner().discover_migrations(version_filter="00")
    return [
        (v, n, p.read_text(encoding="utf-8"))
        for v, n, p in found
        if from_version is None or v > from_version
    ]


def render_sql(migrations: List[Tuple[str, str, str]]) -> str:
    parts = []
    for version, name, sql in migrations:
        parts.append(f"-- soniq migration {version}_{name}\n{sql.rstrip()}\n")
    return "\n".join(parts)


def _literal(sql: str) -> str:
    """Python source for ``sql`` with colons escaped for sqlalchemy.text()."""
    sql = _COLON.sub(lambda m: "\\:", sql)
    if '"""' in sql or sql.replace("\\:", "").count("\\"):
        return repr(sql)
    return '"""' + sql.replace("\\:", "\\\\:") + '"""'


def render_alembic(
    migrations: List[Tuple[str, str, str]],
    down_revision: Optional[str],
    revision: str,
) -> str:
    out = [
        f'"""Soniq schema up to {migrations[-1][0]}.\n\n'
        "Generated by 'soniq migrations export --alembic'. It runs Soniq's SQL\n"
        "migrations and records them in soniq_migrations, so 'soniq setup'\n"
        'finds nothing left to apply.\n"""\n',
        "from alembic import op\n",
        f"revision = {revision!r}",
        f"down_revision = {down_revision!r}",
        "branch_labels = None",
        "depends_on = None\n",
        f"TRACKING_DDL = {_literal(_TRACKING_DDL)}\n",
        "MIGRATIONS = [",
    ]
    for version, name, sql in migrations:
        out.append(f"    ({version!r}, {name!r}, {_literal(sql)}),")
    out += [
        "]\n\n",
        "def upgrade():",
        "    op.execute(TRACKING_DDL)",
        "    for version, name, sql in MIGRATIONS:",
        "        op.execute(sql)",
        "        op.execute(",
        '            "INSERT INTO soniq_migrations (version, name, applied_at) "',
        "            f\"VALUES ('{version}', '{name}', NOW()) \"",
        '            "ON CONFLICT (version) DO NOTHING"',
        "        )\n\n",
        "def downgrade():",
        "    raise NotImplementedError(",
        '        "Soniq migrations have no downgrade; drop the soniq_* tables by hand"',
        "    )\n",
    ]
    return "\n".join(out)


def handle_export(args) -> int:
    migrations = _select(args.from_version)
    if not migrations:
        print("No migrations to export", file=sys.stderr)
        return 1
    if args.sql:
        sys.stdout.write(render_sql(migrations))
    else:
        revision = args.revision or f"soniq_{migrations[-1][0]}"
        sys.stdout.write(render_alembic(migrations, args.down_revision, revision))
    return 0
